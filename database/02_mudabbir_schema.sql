    summary_id  NUMBER(10)  NOT NULL,
    CONSTRAINT pk_subject_summary          PRIMARY KEY (subject_id, summary_id),
    CONSTRAINT fk_subject_summary_subject    FOREIGN KEY (subject_id)   REFERENCES subject (subject_id),
    CONSTRAINT fk_subject_summary_summary  FOREIGN KEY (summary_id) REFERENCES summary (summary_id)
);
CREATE INDEX ix_subject_summary_summary ON subject_summary (summary_id);

-- ---------------------------------------------------------------------
-- SUBJECT_KHUTBA
