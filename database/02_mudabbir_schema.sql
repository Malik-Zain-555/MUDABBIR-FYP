-- 02_mudabbir_schema.sql
-- Mudabbir: the remaining 32 tables, built to match the ERD
--
-- RUN AFTER : 01_quran_core.sql  (it already created SURAH, AYAT,
--             TRANSLATOR, TRANSLATION - do NOT recreate them)
-- CONNECT AS: mudabbir_dev  (user MUDABBIR)
-- HOW       : File > Open, then F5 (Run Script)
--
-- RESULT    : 4 existing + 32 new = 36 tables (as in the ERD)
--
-- CONVENTIONS
--   * snake_case names, VARCHAR2(n CHAR) for text, AL32UTF8 safe
--   * User entity  -> table APP_USER (USER is reserved in Oracle)
--   * Surrogate keys use identity columns
--     (GENERATED BY DEFAULT ON NULL: auto-numbered, but you may also
--      supply your own value when importing)
--   * Subtype tables (SCHOLAR, LEARNER, ADMIN) reuse the user_id as
--     their own key, so they have NO identity column. Each also keeps a
--     fixed "role" value, so the database refuses a SCHOLAR row for a
--     user whose role is LEARNER (and the same for the other roles)
--   * Topic is called SUBJECT everywhere (as in the ERD and use cases)
--   * Constraint names: pk_ / fk_ / uq_ / ck_ ; index names: ix_
--   * Oracle does not index foreign keys automatically, so the
--     ix_ indexes below are there on purpose
-- =====================================================================


-- =====================================================================
-- MODULE 4 - USER RECORDS (created first: other tables point to them)
-- =====================================================================

-- ---------------------------------------------------------------------
-- APP_USER : supertype of Learner, Scholar, Admin
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    user_id         NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    full_name       VARCHAR2(100 CHAR)   NOT NULL,
    email           VARCHAR2(150 CHAR)   NOT NULL,
    password_hash   VARCHAR2(255 CHAR)   NOT NULL,
    phone_no        VARCHAR2(20 CHAR),
    role            VARCHAR2(10 CHAR)    NOT NULL,
    account_status  VARCHAR2(10 CHAR)    DEFAULT 'PENDING' NOT NULL,
    created_at      TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user        PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email  UNIQUE (email),
    CONSTRAINT uq_app_user_id_role UNIQUE (user_id, role),
    CONSTRAINT ck_app_user_role   CHECK (role IN ('LEARNER', 'SCHOLAR', 'ADMIN')),
    CONSTRAINT ck_app_user_status CHECK (account_status IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED'))
);

-- ---------------------------------------------------------------------
-- ADMIN
-- ---------------------------------------------------------------------
CREATE TABLE admin (
    admin_id     NUMBER(10)           NOT NULL,
    role         VARCHAR2(10 CHAR)    DEFAULT 'ADMIN' NOT NULL,
    designation  VARCHAR2(100 CHAR),
    CONSTRAINT pk_admin       PRIMARY KEY (admin_id),
    CONSTRAINT ck_admin_role  CHECK (role = 'ADMIN'),
    CONSTRAINT fk_admin_user  FOREIGN KEY (admin_id, role) REFERENCES app_user (user_id, role)
);

-- ---------------------------------------------------------------------
-- SCHOLAR : the approval itself is kept in SCHOLAR_APPROVAL (below)
-- ---------------------------------------------------------------------
CREATE TABLE scholar (
    scholar_id      NUMBER(10)           NOT NULL,
    role            VARCHAR2(10 CHAR)    DEFAULT 'SCHOLAR' NOT NULL,
    qualification   VARCHAR2(200 CHAR),
    specialization  VARCHAR2(200 CHAR),
    CONSTRAINT pk_scholar          PRIMARY KEY (scholar_id),
    CONSTRAINT ck_scholar_role     CHECK (role = 'SCHOLAR'),
    CONSTRAINT fk_scholar_user     FOREIGN KEY (scholar_id, role) REFERENCES app_user (user_id, role)
);

-- ---------------------------------------------------------------------
-- SCHOLAR_APPROVAL (weak entity of SCHOLAR): a Scholar submits a request,
-- an Admin approves or rejects it. Keeps the history of every request.
-- ---------------------------------------------------------------------
CREATE TABLE scholar_approval (
    scholar_id      NUMBER(10)           NOT NULL,
    request_no      NUMBER(3)            NOT NULL,
    submitted_at    TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    request_status  VARCHAR2(10 CHAR)    DEFAULT 'PENDING' NOT NULL,
    reviewed_by     NUMBER(10),
    reviewed_at     TIMESTAMP,
    remarks         VARCHAR2(500 CHAR),
    CONSTRAINT pk_scholar_approval          PRIMARY KEY (scholar_id, request_no),
    CONSTRAINT fk_scholar_approval_scholar  FOREIGN KEY (scholar_id)  REFERENCES scholar (scholar_id),
    CONSTRAINT fk_scholar_approval_admin    FOREIGN KEY (reviewed_by) REFERENCES admin (admin_id),
    CONSTRAINT ck_scholar_approval_status   CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_scholar_approval_review   CHECK (
        (request_status = 'PENDING'  AND reviewed_by IS NULL     AND reviewed_at IS NULL) OR
        (request_status <> 'PENDING' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX ix_scholar_approval_reviewer ON scholar_approval (reviewed_by);

-- ---------------------------------------------------------------------
-- LEARNER
-- ---------------------------------------------------------------------
CREATE TABLE learner (
    learner_id       NUMBER(10)          NOT NULL,
    role             VARCHAR2(10 CHAR)   DEFAULT 'LEARNER' NOT NULL,
    education_level  VARCHAR2(50 CHAR),
    country          VARCHAR2(60 CHAR),
    CONSTRAINT pk_learner       PRIMARY KEY (learner_id),
    CONSTRAINT ck_learner_role  CHECK (role = 'LEARNER'),
    CONSTRAINT fk_learner_user  FOREIGN KEY (learner_id, role) REFERENCES app_user (user_id, role)
);


