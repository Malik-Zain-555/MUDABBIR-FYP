-- ---------------------------------------------------------------------
-- MCC_OFFERING : a run of an MCC, set up by an Admin, taught by a Scholar
-- ---------------------------------------------------------------------
CREATE TABLE mcc_offering (
    offering_id      NUMBER(10)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
    mcc_id           NUMBER(10)      NOT NULL,
    scholar_id       NUMBER(10)      NOT NULL,
    admin_id         NUMBER(10)      NOT NULL,
    start_date       DATE            NOT NULL,
    end_date         DATE            NOT NULL,
    fee_amount       NUMBER(10,2)    NOT NULL,
    capacity         NUMBER(4),
    offering_status  VARCHAR2(15 CHAR) DEFAULT 'SCHEDULED' NOT NULL,
    CONSTRAINT pk_mcc_offering          PRIMARY KEY (offering_id),
    CONSTRAINT fk_mcc_offering_mcc      FOREIGN KEY (mcc_id)     REFERENCES mcc (mcc_id),
    CONSTRAINT fk_mcc_offering_scholar  FOREIGN KEY (scholar_id) REFERENCES scholar (scholar_id),
    CONSTRAINT fk_mcc_offering_admin    FOREIGN KEY (admin_id)   REFERENCES admin (admin_id),
    CONSTRAINT ck_mcc_offering_dates    CHECK (end_date >= start_date),
    CONSTRAINT ck_mcc_offering_fee      CHECK (fee_amount >= 0),
    CONSTRAINT ck_mcc_offering_capacity CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT ck_mcc_offering_status   CHECK (offering_status IN ('SCHEDULED', 'OPEN', 'CLOSED', 'COMPLETED', 'CANCELLED'))
);
CREATE INDEX ix_mcc_offering_mcc     ON mcc_offering (mcc_id);
CREATE INDEX ix_mcc_offering_scholar ON mcc_offering (scholar_id);
CREATE INDEX ix_mcc_offering_admin   ON mcc_offering (admin_id);

-- ---------------------------------------------------------------------
-- REGISTRATION : a Learner registers for an offering (only once)
-- ---------------------------------------------------------------------
CREATE TABLE registration (
    registration_id  NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    learner_id       NUMBER(10)   NOT NULL,
    offering_id      NUMBER(10)   NOT NULL,
    registered_at    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_registration           PRIMARY KEY (registration_id),
    CONSTRAINT fk_registration_learner   FOREIGN KEY (learner_id)  REFERENCES learner (learner_id),
    CONSTRAINT fk_registration_offering  FOREIGN KEY (offering_id) REFERENCES mcc_offering (offering_id),
    CONSTRAINT uq_registration_once      UNIQUE (learner_id, offering_id)
);
CREATE INDEX ix_registration_offering ON registration (offering_id);

-- ---------------------------------------------------------------------
-- REGISTRATION_STATUS (weak entity): status history, verified by Admin
-- ---------------------------------------------------------------------
CREATE TABLE registration_status (
    registration_id  NUMBER(10)           NOT NULL,
    status_no        NUMBER(3)            NOT NULL,
    verified_by      NUMBER(10),
    status_code      VARCHAR2(15 CHAR)    NOT NULL,
    status_at        TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    remarks          VARCHAR2(500 CHAR),
    CONSTRAINT pk_registration_status        PRIMARY KEY (registration_id, status_no),
    CONSTRAINT fk_reg_status_registration    FOREIGN KEY (registration_id) REFERENCES registration (registration_id),
    CONSTRAINT fk_reg_status_admin           FOREIGN KEY (verified_by)     REFERENCES admin (admin_id),
    CONSTRAINT ck_reg_status_code            CHECK (status_code IN ('PENDING_PAYMENT', 'PAID', 'VERIFIED', 'REJECTED', 'CANCELLED'))
);
CREATE INDEX ix_reg_status_verifier ON registration_status (verified_by);

-- ---------------------------------------------------------------------
-- PAYMENT (weak entity of REGISTRATION)
-- ---------------------------------------------------------------------
CREATE TABLE payment (
    registration_id  NUMBER(10)           NOT NULL,
    payment_no       NUMBER(3)            NOT NULL,
    amount           NUMBER(10,2)         NOT NULL,
    payment_method   VARCHAR2(30 CHAR)    NOT NULL,
    transaction_ref  VARCHAR2(60 CHAR),
    paid_at          TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_payment               PRIMARY KEY (registration_id, payment_no),
    CONSTRAINT fk_payment_registration  FOREIGN KEY (registration_id) REFERENCES registration (registration_id),
    CONSTRAINT ck_payment_amount        CHECK (amount > 0)
);


