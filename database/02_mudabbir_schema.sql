    title        VARCHAR2(200 CHAR)    NOT NULL,
    description  VARCHAR2(2000 CHAR),
    mcc_status   VARCHAR2(15 CHAR)     DEFAULT 'DRAFT' NOT NULL,
    created_at   DATE                  DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_mcc          PRIMARY KEY (mcc_id),
    CONSTRAINT fk_mcc_scholar  FOREIGN KEY (scholar_id) REFERENCES scholar (scholar_id),
    CONSTRAINT ck_mcc_status   CHECK (mcc_status IN ('DRAFT', 'PUBLISHED', 'RETIRED'))
);
CREATE INDEX ix_mcc_scholar ON mcc (scholar_id);

-- ---------------------------------------------------------------------
-- SUBJECT_MCC : subjects covered by an MCC, in order
-- ---------------------------------------------------------------------
CREATE TABLE subject_mcc (
    subject_id     NUMBER(10)  NOT NULL,
    mcc_id       NUMBER(10)  NOT NULL,
    sequence_no  NUMBER(3)   NOT NULL,
    CONSTRAINT pk_subject_mcc        PRIMARY KEY (subject_id, mcc_id),
    CONSTRAINT fk_subject_mcc_subject  FOREIGN KEY (subject_id) REFERENCES subject (subject_id),
    CONSTRAINT fk_subject_mcc_mcc    FOREIGN KEY (mcc_id)   REFERENCES mcc (mcc_id)
);
CREATE INDEX ix_subject_mcc_mcc ON subject_mcc (mcc_id);

-- ---------------------------------------------------------------------
-- MCC_CONTENT (weak entity of MCC)
-- ---------------------------------------------------------------------
CREATE TABLE mcc_content (
    mcc_id           NUMBER(10)           NOT NULL,
    content_no       NUMBER(3)            NOT NULL,
    added_by         NUMBER(10),
    content_title    VARCHAR2(200 CHAR)   NOT NULL,
    content_format   VARCHAR2(15 CHAR)    NOT NULL,
    content_url      VARCHAR2(500 CHAR),
    approval_status  VARCHAR2(10 CHAR)    DEFAULT 'PENDING' NOT NULL,
    added_at         TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_mcc_content          PRIMARY KEY (mcc_id, content_no),
    CONSTRAINT fk_mcc_content_mcc      FOREIGN KEY (mcc_id)   REFERENCES mcc (mcc_id),
    CONSTRAINT fk_mcc_content_scholar  FOREIGN KEY (added_by) REFERENCES scholar (scholar_id),
    CONSTRAINT ck_mcc_content_approval CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED'))
);
CREATE INDEX ix_mcc_content_added_by ON mcc_content (added_by);


