-- ---------------------------------------------------------------------
-- SUBJECT (a Quranic subject; "Topic" in the old design)
-- scholar_id is empty for subjects imported from the concepts data
-- ---------------------------------------------------------------------
CREATE TABLE subject (
    subject_id     NUMBER(10)            GENERATED BY DEFAULT ON NULL AS IDENTITY,
    scholar_id   NUMBER(10),
    subject_name   VARCHAR2(200 CHAR)    NOT NULL,
    category     VARCHAR2(100 CHAR),
    description  VARCHAR2(1000 CHAR),
    created_at   DATE                  DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_subject          PRIMARY KEY (subject_id),
    CONSTRAINT fk_subject_scholar  FOREIGN KEY (scholar_id) REFERENCES scholar (scholar_id)
);
CREATE INDEX ix_subject_scholar ON subject (scholar_id);
CREATE INDEX ix_subject_name    ON subject (subject_name);

-- ---------------------------------------------------------------------
-- TAFSEER : at least one of English / Urdu must be filled
-- ---------------------------------------------------------------------
CREATE TABLE tafseer (
    tafseer_id    NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ayat_id       NUMBER(6)            NOT NULL,
    author_name   VARCHAR2(100 CHAR),
    tafseer_eng   CLOB,
    tafseer_urdu  CLOB,
    CONSTRAINT pk_tafseer        PRIMARY KEY (tafseer_id),
    CONSTRAINT fk_tafseer_ayat   FOREIGN KEY (ayat_id) REFERENCES ayat (ayat_id),
    CONSTRAINT ck_tafseer_text   CHECK (tafseer_eng IS NOT NULL OR tafseer_urdu IS NOT NULL)
);
CREATE INDEX ix_tafseer_ayat ON tafseer (ayat_id);

-- ---------------------------------------------------------------------
-- SUBJECT_AYAT : which ayat belong to which subject (+ AI relevance score)
-- approved_by / approved_at empty until a Scholar reviews the link
-- ---------------------------------------------------------------------
CREATE TABLE subject_ayat (
    subject_id         NUMBER(10)   NOT NULL,
    ayat_id          NUMBER(6)    NOT NULL,
    relevance_score  NUMBER(5,2),
    approved_by      NUMBER(10),
    approved_at      TIMESTAMP,
    CONSTRAINT pk_subject_ayat          PRIMARY KEY (subject_id, ayat_id),
    CONSTRAINT fk_subject_ayat_subject    FOREIGN KEY (subject_id)    REFERENCES subject (subject_id),
    CONSTRAINT fk_subject_ayat_ayat     FOREIGN KEY (ayat_id)     REFERENCES ayat (ayat_id),
    CONSTRAINT fk_subject_ayat_scholar  FOREIGN KEY (approved_by) REFERENCES scholar (scholar_id),
    CONSTRAINT ck_subject_ayat_approval CHECK (
        (approved_by IS NULL AND approved_at IS NULL) OR
        (approved_by IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE INDEX ix_subject_ayat_ayat     ON subject_ayat (ayat_id);
CREATE INDEX ix_subject_ayat_approver ON subject_ayat (approved_by);

-- ---------------------------------------------------------------------
-- SUBJECT_SURAH
-- ---------------------------------------------------------------------
CREATE TABLE subject_surah (
    subject_id   NUMBER(10)  NOT NULL,
    surah_id   NUMBER(3)   NOT NULL,
    CONSTRAINT pk_subject_surah        PRIMARY KEY (subject_id, surah_id),
    CONSTRAINT fk_subject_surah_subject  FOREIGN KEY (subject_id) REFERENCES subject (subject_id),
    CONSTRAINT fk_subject_surah_surah  FOREIGN KEY (surah_id) REFERENCES surah (surah_id)
);
CREATE INDEX ix_subject_surah_surah ON subject_surah (surah_id);

-- ---------------------------------------------------------------------
-- AYAT_QUESTION (weak entity of AYAT)
-- ---------------------------------------------------------------------
CREATE TABLE ayat_question (
    ayat_id          NUMBER(6)             NOT NULL,
    question_no      NUMBER(3)             NOT NULL,
    subject_id         NUMBER(10)            NOT NULL,
    question_text    VARCHAR2(4000 CHAR)   NOT NULL,
    question_format  VARCHAR2(20 CHAR)     NOT NULL,
    answer_key       VARCHAR2(4000 CHAR),
    CONSTRAINT pk_ayat_question        PRIMARY KEY (ayat_id, question_no),
    CONSTRAINT fk_ayat_question_ayat   FOREIGN KEY (ayat_id)  REFERENCES ayat (ayat_id),
    CONSTRAINT fk_ayat_question_subject  FOREIGN KEY (subject_id) REFERENCES subject (subject_id)
);
CREATE INDEX ix_ayat_question_subject ON ayat_question (subject_id);


