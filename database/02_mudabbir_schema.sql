    question_order  NUMBER(3),
    CONSTRAINT pk_assessment_question             PRIMARY KEY (assessment_id, ayat_id, question_no),
    CONSTRAINT fk_assessment_question_assessment  FOREIGN KEY (assessment_id)         REFERENCES assessment (assessment_id),
    CONSTRAINT fk_assessment_question_question    FOREIGN KEY (ayat_id, question_no)  REFERENCES ayat_question (ayat_id, question_no),
    CONSTRAINT ck_assessment_question_marks       CHECK (marks > 0)
);
CREATE INDEX ix_assessment_question_question ON assessment_question (ayat_id, question_no);

-- ---------------------------------------------------------------------
-- ASSESSMENT_ATTEMPT : a registered learner attempts an assessment
-- uq_attempt_assessment lets LEARNER_ANSWER point at (attempt, assessment)
-- ---------------------------------------------------------------------
CREATE TABLE assessment_attempt (
    attempt_id       NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    assessment_id    NUMBER(10)   NOT NULL,
    registration_id  NUMBER(10)   NOT NULL,
    attempt_no       NUMBER(2)    NOT NULL,
    started_at       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    submitted_at     TIMESTAMP,
    CONSTRAINT pk_assessment_attempt             PRIMARY KEY (attempt_id),
    CONSTRAINT uq_attempt_assessment             UNIQUE (attempt_id, assessment_id),
    CONSTRAINT uq_attempt_per_registration       UNIQUE (assessment_id, registration_id, attempt_no),
    CONSTRAINT fk_assessment_attempt_assessment  FOREIGN KEY (assessment_id)   REFERENCES assessment (assessment_id),
    CONSTRAINT fk_assessment_attempt_reg         FOREIGN KEY (registration_id) REFERENCES registration (registration_id),
    CONSTRAINT ck_assessment_attempt_time        CHECK (submitted_at IS NULL OR submitted_at >= started_at)
);
CREATE INDEX ix_assessment_attempt_reg ON assessment_attempt (registration_id);

-- ---------------------------------------------------------------------
-- LEARNER_ANSWER : an answer to one question inside one attempt.
-- Two composite FKs guarantee the question belongs to the SAME
-- assessment as the attempt (business rule 8).
-- ---------------------------------------------------------------------
CREATE TABLE learner_answer (
    attempt_id      NUMBER(10)            NOT NULL,
    ayat_id         NUMBER(6)             NOT NULL,
    question_no     NUMBER(3)             NOT NULL,
    assessment_id   NUMBER(10)            NOT NULL,
    answer_text     VARCHAR2(4000 CHAR),
    is_correct      VARCHAR2(1 CHAR),
    marks_obtained  NUMBER(4,1),
    answered_at     TIMESTAMP,
    CONSTRAINT pk_learner_answer          PRIMARY KEY (attempt_id, ayat_id, question_no),
    CONSTRAINT fk_learner_answer_attempt  FOREIGN KEY (attempt_id, assessment_id)
        REFERENCES assessment_attempt (attempt_id, assessment_id),
    CONSTRAINT fk_learner_answer_question FOREIGN KEY (assessment_id, ayat_id, question_no)
        REFERENCES assessment_question (assessment_id, ayat_id, question_no),
    CONSTRAINT ck_learner_answer_correct  CHECK (is_correct IS NULL OR is_correct IN ('Y', 'N')),
    CONSTRAINT ck_learner_answer_marks    CHECK (marks_obtained IS NULL OR marks_obtained >= 0)
);
CREATE INDEX ix_learner_answer_question ON learner_answer (assessment_id, ayat_id, question_no);
CREATE INDEX ix_learner_answer_attempt  ON learner_answer (attempt_id, assessment_id);

-- ---------------------------------------------------------------------
-- ASSESSMENT_RESULT (weak entity): one per attempt
-- ---------------------------------------------------------------------
CREATE TABLE assessment_result (
    attempt_id      NUMBER(10)    NOT NULL,
    marks_obtained  NUMBER(5,2)   NOT NULL,
    percentage      NUMBER(5,2)   NOT NULL,
    result_status   VARCHAR2(10 CHAR) NOT NULL,
    CONSTRAINT pk_assessment_result          PRIMARY KEY (attempt_id),
    CONSTRAINT fk_assessment_result_attempt  FOREIGN KEY (attempt_id) REFERENCES assessment_attempt (attempt_id),
    CONSTRAINT ck_assessment_result_pct      CHECK (percentage BETWEEN 0 AND 100),
    CONSTRAINT ck_assessment_result_marks    CHECK (marks_obtained >= 0),
    CONSTRAINT ck_assessment_result_status   CHECK (result_status IN ('PASS', 'FAIL'))
);


