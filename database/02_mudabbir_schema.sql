    CONSTRAINT pk_subject_khutba         PRIMARY KEY (subject_id, khutba_id),
    CONSTRAINT fk_subject_khutba_subject   FOREIGN KEY (subject_id)  REFERENCES subject (subject_id),
    CONSTRAINT fk_subject_khutba_khutba  FOREIGN KEY (khutba_id) REFERENCES khutba (khutba_id)
);
CREATE INDEX ix_subject_khutba_khutba ON subject_khutba (khutba_id);

-- ---------------------------------------------------------------------
-- AI_GENERATED_CONTENT
-- Exactly one of summary_id / khutba_id must be filled.
-- Learners see it only when approval_status = 'APPROVED'.
-- ---------------------------------------------------------------------
CREATE TABLE ai_generated_content (
    content_id       NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    subject_id         NUMBER(10)   NOT NULL,
    requested_by     NUMBER(10)   NOT NULL,
    approved_by      NUMBER(10),
    summary_id       NUMBER(10),
    khutba_id        NUMBER(10),
    generated_text   CLOB         NOT NULL,
    approval_status  VARCHAR2(10 CHAR) DEFAULT 'PENDING' NOT NULL,
    created_at       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    approved_at      TIMESTAMP,
    CONSTRAINT pk_ai_content           PRIMARY KEY (content_id),
    CONSTRAINT fk_ai_content_subject     FOREIGN KEY (subject_id)     REFERENCES subject (subject_id),
    CONSTRAINT fk_ai_content_learner   FOREIGN KEY (requested_by) REFERENCES learner (learner_id),
    CONSTRAINT fk_ai_content_scholar   FOREIGN KEY (approved_by)  REFERENCES scholar (scholar_id),
    CONSTRAINT fk_ai_content_summary   FOREIGN KEY (summary_id)   REFERENCES summary (summary_id),
    CONSTRAINT fk_ai_content_khutba    FOREIGN KEY (khutba_id)    REFERENCES khutba (khutba_id),
    CONSTRAINT uq_ai_content_summary   UNIQUE (summary_id),
    CONSTRAINT uq_ai_content_khutba    UNIQUE (khutba_id),
    CONSTRAINT ck_ai_content_status    CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_ai_content_one_of    CHECK (
        (summary_id IS NOT NULL AND khutba_id IS NULL) OR
        (summary_id IS NULL AND khutba_id IS NOT NULL))
);
CREATE INDEX ix_ai_content_subject     ON ai_generated_content (subject_id);
CREATE INDEX ix_ai_content_requester ON ai_generated_content (requested_by);
CREATE INDEX ix_ai_content_approver  ON ai_generated_content (approved_by);


